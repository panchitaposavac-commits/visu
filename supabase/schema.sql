-- ------------------------------------------------------------------------------
-- 6. CONFIGURACIÓN DEL STORAGE BUCKET PARA EVIDENCIAS FOTOGRÁFICAS
-- ------------------------------------------------------------------------------
-- Crea el bucket 'visu-evidencias' utilizado en el módulo de recepción y diagnóstico
INSERT INTO storage.buckets (id, name, public)
VALUES ('visu-evidencias', 'visu-evidencias', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage para visu-evidencias
DROP POLICY IF EXISTS "Acceso publico lectura visu-evidencias" ON storage.objects;
CREATE POLICY "Acceso publico lectura visu-evidencias"
    ON storage.objects FOR SELECT
    TO anon, authenticated
    USING (bucket_id = 'visu-evidencias');

DROP POLICY IF EXISTS "Subida publica visu-evidencias" ON storage.objects;
CREATE POLICY "Subida publica visu-evidencias"
    ON storage.objects FOR INSERT
    TO anon, authenticated
    WITH CHECK (bucket_id = 'visu-evidencias');

DROP POLICY IF EXISTS "Actualizacion publica visu-evidencias" ON storage.objects;
CREATE POLICY "Actualizacion publica visu-evidencias"
    ON storage.objects FOR UPDATE
    TO anon, authenticated
    USING (bucket_id = 'visu-evidencias');
