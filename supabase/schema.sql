-- Incluye:
-- 1. Habilitación de extensiones necesarias (UUID / pgcrypto)
-- 2. Creación de tipos ENUM personalizados
-- 3. Creación de las 5 tablas con llaves primarias UUID gen_random_uuid(),
--    llaves foráneas e integridad referencial
-- 4. Habilitación de Row Level Security (RLS) en todas las tablas
-- 5. Creación de Políticas de Seguridad RLS exactas (anon / authenticated)
-- 6. Configuración del Storage Bucket 'visu-evidencias' y sus políticas RLS
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. EXTENSIONES
-- ------------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ------------------------------------------------------------------------------
-- 2. TIPOS PERSONALIZADOS (ENUMS)
-- ------------------------------------------------------------------------------
DO $$ BEGIN
    CREATE TYPE estado_orden_trabajo AS ENUM (
        'recibido',
        'en_proceso',
        'listo',
        'entregado',
        'cancelado',
        'en_revision',
        'esperando_aprobacion',
        'en_reparacion'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE tipo_servicio AS ENUM (
        'mantencion',
        'reparacion'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE etapa_evidencia AS ENUM (
        'recepcion',
        'entrega'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

-- ------------------------------------------------------------------------------
-- 3. CREACIÓN DE TABLAS
-- ------------------------------------------------------------------------------

-- Tabla 1: clientes
CREATE TABLE IF NOT EXISTS clientes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    rut_dni VARCHAR UNIQUE,
    nombre VARCHAR NOT NULL,
    apellido VARCHAR,
    correo VARCHAR UNIQUE,
    telefono VARCHAR,
    creado_el TIMESTAMPTZ DEFAULT now(),
    actualizado_el TIMESTAMPTZ DEFAULT now()
);

-- Tabla 2: vehiculos
CREATE TABLE IF NOT EXISTS vehiculos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cliente_id UUID REFERENCES clientes(id) ON DELETE SET NULL,
    patente VARCHAR UNIQUE NOT NULL,
    marca VARCHAR NOT NULL,
    modelo VARCHAR NOT NULL,
    anio INT4 NOT NULL,
    kilometraje INT4 NOT NULL,
    color VARCHAR,
    creado_el TIMESTAMPTZ DEFAULT now(),
    actualizado_el TIMESTAMPTZ DEFAULT now()
);

-- Tabla 3: ordenes_trabajo
CREATE TABLE IF NOT EXISTS ordenes_trabajo (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    numero_ot INT4 GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    cliente_id UUID REFERENCES clientes(id) ON DELETE RESTRICT,
    vehiculo_id UUID REFERENCES vehiculos(id) ON DELETE RESTRICT,
    tipo_servicio tipo_servicio NOT NULL,
    estado estado_orden_trabajo NOT NULL DEFAULT 'recibido',
    descripcion_cliente TEXT NOT NULL,
    notas_diagnostico TEXT,
    fecha_estimada_entrega TIMESTAMPTZ,
    fecha_entregado TIMESTAMPTZ,
    url_pdf_recepcion TEXT,
    creado_por UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    creado_el TIMESTAMPTZ DEFAULT now(),
    actualizado_el TIMESTAMPTZ DEFAULT now()
);

-- Tabla 4: evidencias_orden
CREATE TABLE IF NOT EXISTS evidencias_orden (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    orden_trabajo_id UUID NOT NULL REFERENCES ordenes_trabajo(id) ON DELETE CASCADE,
    etapa etapa_evidencia NOT NULL DEFAULT 'recepcion',
    seccion VARCHAR NOT NULL,
    url_archivo TEXT NOT NULL,
    notas TEXT,
    subido_el TIMESTAMPTZ DEFAULT now()
);

-- Tabla 5: hallazgos_ot
CREATE TABLE IF NOT EXISTS hallazgos_ot (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    orden_trabajo_id UUID NOT NULL REFERENCES ordenes_trabajo(id) ON DELETE CASCADE,
    titulo VARCHAR NOT NULL,
    descripcion TEXT NOT NULL,
    foto_url TEXT,
    precio_neto NUMERIC,
    creado_el TIMESTAMPTZ DEFAULT now(),
    url_foto TEXT,
    valor_neto NUMERIC
);

-- Índices recomendados para optimización de consultas y llaves foráneas
CREATE INDEX IF NOT EXISTS idx_vehiculos_cliente_id ON vehiculos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_vehiculos_patente ON vehiculos(patente);
CREATE INDEX IF NOT EXISTS idx_ordenes_trabajo_cliente_id ON ordenes_trabajo(cliente_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_trabajo_vehiculo_id ON ordenes_trabajo(vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_trabajo_estado ON ordenes_trabajo(estado);
CREATE INDEX IF NOT EXISTS idx_evidencias_orden_ot_id ON evidencias_orden(orden_trabajo_id);
CREATE INDEX IF NOT EXISTS idx_hallazgos_ot_ot_id ON hallazgos_ot(orden_trabajo_id);

-- ------------------------------------------------------------------------------
-- 4. HABILITACIÓN DE ROW LEVEL SECURITY (RLS)
-- ------------------------------------------------------------------------------
ALTER TABLE clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE vehiculos ENABLE ROW LEVEL SECURITY;
ALTER TABLE ordenes_trabajo ENABLE ROW LEVEL SECURITY;
ALTER TABLE evidencias_orden ENABLE ROW LEVEL SECURITY;
ALTER TABLE hallazgos_ot ENABLE ROW LEVEL SECURITY;

